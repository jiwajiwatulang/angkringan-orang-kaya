import 'fake-indexeddb/auto';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {environment,owner} from './multideviceFixtures';
import {submitEvent,pullEntities} from '../src/lib/server/multideviceSync';
import {setPosScope} from '../src/lib/multidevice/posWire';

test('actual POS operations commit one durable event atomically and reconcile split payments and edits',async()=>{
  const env=await environment(),o=await owner(env);
  process.env.NEXT_PUBLIC_SAKUNOTA_MULTI_DEVICE='enabled';
  const storage=new Map<string,string>([['sakunota_pos_partition',JSON.stringify({storeId:o.claims.storeId,deviceId:o.id})]]);
  Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(key:string)=>storage.get(key)||null,setItem:(key:string,value:string)=>storage.set(key,value),removeItem:(key:string)=>storage.delete(key)}});
  const {db}=await import('../src/lib/dexie');const api=await import('../src/lib/api');const inventory=await import('../src/lib/inventory');
  setPosScope({claims:o.claims,access:o.access,operatorName:'Pemilik'});
  const flush=async()=>{for(const row of await db.table('posOutbox').orderBy('ordinal').toArray()){await submitEvent(env.DB,o.claims,row.event);await submitEvent(env.DB,o.claims,row.event);await db.table('posOutbox').delete(row.id);}};
  try{
    await db.table('settings').put({key:'pos_store_settings',value:{storeName:'Warung QA',enableTax:false,enableService:false}});
    const product=await api.createMenu({nama:'Kopi',harga:10000,kategori:'Minuman'});
    await inventory.configureStock(Number(product),20);
    await api.openShift({operatorName:'Pemilik',startingCash:50000});await flush();
    const input={status:'unpaid',total:20000,subtotal:20000,items:[{id:Number(product),nama:'Kopi',harga:10000,qty:2}]};
    const note=await api.createOrder(input);
    assert.equal(await db.table('posOutbox').count(),1);
    await flush();
    await api.updateOrder(Number(note.id),{...input,total:30000,subtotal:30000,items:[{id:Number(product),nama:'Kopi',harga:10000,qty:3}]});await flush();
    await api.recordPayment({orderId:Number(note.id),paymentMethod:'Cash',amount:10000,splitType:'partial',operatorName:'Pemilik'});await flush();
    await api.recordPayment({orderId:Number(note.id),paymentMethod:'QRIS',amount:20000,splitType:'partial',operatorName:'Pemilik'});await flush();
    const entities=(await pullEntities(env.DB,o.claims,0)).entities;
    const canonical=entities.find(row=>row.kind==='pos_orders')!.value;
    assert.equal(canonical.total,30000);assert.equal(canonical.paidAmount,30000);assert.equal(canonical.remainingBalance,0);
    assert.equal(entities.filter(row=>row.kind==='pos_payments').length,2);
    assert.equal(entities.find(row=>row.kind==='pos_menuItems')!.value.stockQty,17);
    const shift=await api.getActiveShift();await api.closeShift(shift.id,{actualCash:60000});await flush();
    const closed=(await pullEntities(env.DB,o.claims,0)).entities.find(row=>row.kind==='pos_shifts')!.value;
    await api.openShift({operatorName:'Pemilik',startingCash:20000});await flush();
    const cash=(await db.table('payments').toArray()).find(row=>row.paymentMethod==='Cash');
    await api.refundPartialPayment(cash.id,{reason:'Koreksi pembayaran',operator:'Pemilik'});await flush();
    const refunded=(await pullEntities(env.DB,o.claims,0)).entities;
    assert.equal(refunded.find(row=>row.kind==='pos_orders')!.value.paidAmount,20000);
    assert.deepEqual(refunded.find(row=>row.kind==='pos_shifts'&&row.id===closed.mdId)!.value,closed);
    const imageData='data:image/png;base64,'+'A'.repeat(2700000);
    await api.createOrder({status:'paid',paymentMethod:'QRIS',total:10000,subtotal:10000,items:[{id:Number(product),nama:'Kopi',harga:10000,qty:1}],proof:{imageData}});await flush();
    const proof=(await pullEntities(env.DB,o.claims,0)).entities.find(row=>row.kind==='pos_paymentProofs')!.value;
    assert.equal(proof.imageData,imageData);
    const parts=await env.DB.prepare('SELECT count(*) n FROM MdPayloadChunks').first<number>('n');assert.ok(Number(parts)>20);
    const retail=await api.createOrder({status:'unpaid',total:5000,items:[{id:-1,nama:'Barang Baru',harga:5000,qty:1,pendingRetailProduct:{nama:'Barang Baru',harga:5000}}]});await flush();
    await api.recordPayment({orderId:Number(retail.id),paymentMethod:'Cash',amount:1000,splitType:'partial',operatorName:'Pemilik'});await flush();
    await api.recordPayment({orderId:Number(retail.id),paymentMethod:'Cash',amount:4000,splitType:'partial',operatorName:'Pemilik'});await flush();
    assert.equal(await db.table('menuItems').where('nama').equals('Barang Baru').count(),1);
    setPosScope({claims:o.claims,access:o.access,operatorName:'Pemilik',importingLegacy:true});
    const legacyProduct=await db.table('menuItems').add({nama:'Beras Lama',harga:5000,kategori:'Sembako',trackStock:true,stockQty:7,isSoldOut:false});await flush();
    const legacyShift=await db.table('shifts').add({operatorName:'Pemilik',status:'closed',startingCash:0,actualCash:12000,endTime:new Date().toISOString()});await flush();
    await db.transaction('rw',['orders','orderItems','payments'],async()=>{
      const id=await db.table('orders').add({status:'paid',shiftId:legacyShift,total:12000,subtotal:12000,paidAmount:12000});
      await db.table('orderItems').add({orderId:id,menuItemId:legacyProduct,namaMenu:'Beras Lama',qty:3,hargaSatuan:4000});
      await db.table('payments').add({orderId:id,shiftId:legacyShift,amount:12000,status:'completed',paymentMethod:'Cash'});
    });await flush();
    await db.table('inventoryMovements').add({menuItemId:legacyProduct,type:'opening',delta:10,balance:10});await flush();
    await db.table('cashMovements').add({shiftId:legacyShift,type:'out',amount:1000});await flush();
    const legacyCanonical=(await pullEntities(env.DB,o.claims,0)).entities.find(row=>row.kind==='pos_menuItems'&&row.value.nama==='Beras Lama')!.value;
    assert.equal(legacyCanonical.stockQty,7);
    setPosScope({claims:o.claims,access:o.access,operatorName:'Pemilik'});
    const before=await db.table('orders').count();
    const quick=(await db.table('menuItems').where('nama').equals('Barang Baru').first())!;
    await assert.rejects(()=>api.createOrder({status:'unpaid',total:3000000,items:Array.from({length:600},()=>({id:quick.id,nama:'Barang Baru',harga:5000,qty:1}))}),/Terlalu banyak/);
    assert.equal(await db.table('orders').count(),before);assert.equal(await db.table('posOutbox').count(),0);
    await assert.rejects(()=>db.transaction('rw',['orders'],async()=>{await db.table('orders').add({status:'unpaid',total:1});throw new Error('rollback');}));
    assert.equal(await db.table('orders').count(),before);assert.equal(await db.table('posOutbox').count(),0);
  }finally{setPosScope(undefined);await db.delete();delete process.env.NEXT_PUBLIC_SAKUNOTA_MULTI_DEVICE;delete (globalThis as any).localStorage;}
});
